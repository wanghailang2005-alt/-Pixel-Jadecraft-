const point=(x,y)=>({x:box.x+(48+x*11)*box.w/480,y:box.y+(28+y*11)*box.h/320});
for(const [x,y] of [[8,6],[13,15]]) {
  const start=point(x-1,y);
  await qa.send('Input.dispatchMouseEvent',{type:'mousePressed',...start,button:'left',clickCount:1});
  for(let dx=-1;dx<=2;dx++)await qa.send('Input.dispatchMouseEvent',{type:'mouseMoved',...point(x+dx,y),button:'left',buttons:1});
  await qa.send('Input.dispatchMouseEvent',{type:'mouseReleased',...point(x+2,y),button:'left',clickCount:1});
}
await qa.click('[data-cord]');
assert.equal(await qa.evaluate(`document.querySelector('[data-deliver]').disabled`),false,'Care must complete with actual brush input');
await qa.screenshot(new URL('story-care-ready.png',dir));
await qa.click('[data-deliver]');
await qa.click('[data-return]');
