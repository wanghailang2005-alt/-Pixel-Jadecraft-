export const JADE_VARIETIES = Object.freeze(Object.fromEntries(varieties.map(
  ([id, name, origin, luster, band, advice, story, palette]) =>
    [id, Object.freeze({ name, origin, luster, band, advice, story, palette })],
)));

export const STARTER_JADES = Object.freeze(varieties.map(([variety], index) => Object.freeze({
  id: index === 0 ? 'mentor-first-jade' : `starter-${variety}`,
  material: variety === 'dushan' ? 'jadeite' : 'nephrite',
  seed: index === 0 ? 220 : 71 + index * 139,
  variety,
})));

export const jadeVariety = stone => Object.hasOwn(JADE_VARIETIES, stone?.variety) ? JADE_VARIETIES[stone.variety] : undefined;
